#!/usr/bin/env node
// Build chatgpt-bundle.md for the DearTech-OS Starter Kit (dt-os-starter-kit).
import { lstatSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(repoRoot, 'chatgpt-bundle.md');
const scanDirs = ['business', 'ops', 'memory'];

function walk(dir) {
  let out = [];
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return out;
  }
  for (const entry of entries) {
    const path = join(dir, entry);
    const stat = lstatSync(path);
    if (stat.isSymbolicLink()) continue;
    if (stat.isDirectory()) out = out.concat(walk(path));
    else if (stat.isFile() && extname(path) === '.md') out.push(path);
  }
  return out.sort();
}

const sources = [
  join(repoRoot, 'node_template.md'),
  ...scanDirs.flatMap((dir) => walk(join(repoRoot, dir))),
];

const chunks = sources.map((path) => {
  const rel = relative(repoRoot, path).split(sep).join('/');
  const body = readFileSync(path, 'utf8').replace(/\s+$/, '');
  return `## ${rel}\n\n${body}`;
});

const banner = `# DearTech-OS Starter Kit: ChatGPT bundle

This file combines the note template and the starter notes into one upload.
Upload this file and AGENTS.md to a ChatGPT Project.
The Free plan allows 5 files per Project. This bundle keeps the upload within that limit.

Generated by \`npm run bundle\`. Do not edit this file by hand.
After you change a note, run \`npm run bundle\` again from the kit folder.

`;

writeFileSync(outputPath, `${banner}${chunks.join('\n\n---\n\n')}\n`);
console.log(`Wrote ${relative(repoRoot, outputPath)} (${sources.length} files)`);
